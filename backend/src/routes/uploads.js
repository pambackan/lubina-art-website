import { Router } from 'express';
import multer from 'multer';
import path from 'node:path';
import fs from 'node:fs';
import { requireAdmin } from '../middleware/auth.js';
const router=Router();const dir=path.resolve(process.cwd(),process.env.UPLOAD_DIR||'uploads');fs.mkdirSync(dir,{recursive:true});
const storage=multer.diskStorage({destination:(_req,_file,cb)=>cb(null,dir),filename:(_req,file,cb)=>cb(null,`${Date.now()}-${Math.random().toString(36).slice(2,8)}${path.extname(file.originalname).toLowerCase()}`)});
const upload=multer({storage,limits:{fileSize:8*1024*1024},fileFilter:(_req,file,cb)=>cb(null,['image/jpeg','image/png','image/webp','image/avif'].includes(file.mimetype))});
router.post('/',requireAdmin,upload.single('image'),(req,res)=>{if(!req.file)return res.status(400).json({message:'Choose a JPG, PNG, WebP or AVIF image under 8 MB.'});res.status(201).json({url:`/uploads/${req.file.filename}`})});
export default router;
